"""
Units of the Zotero script, one concern each.

Each unit renders one fragment of JavaScript from the plan, with the data it needs embedded as a
JSON literal. The fragments run in Tools > Developer > Run JavaScript with "Run as async function"
ticked, and use only calls observed to work with Zotero 10.0.6:
`Zotero.Libraries.userLibraryID`, `Zotero.Items.getByLibraryAndKey`,
`Zotero.Collections.getByLibraryAndKey`, `item.getAttachments`, `Zotero.Items.get`,
`Zotero.Attachments.importFromFile`, `item.inCollection`, `item.addToCollection`, `item.saveTx`,
`item.setType`, `item.setField`, `item.getField`, `item.setCreators`, `Zotero.ItemTypes.getID`,
`Zotero.ItemFields.getID`, `Zotero.ItemFields.isValidForType` and `IOUtils.exists`.

Every write step tests its own postcondition first and skips when it already holds, so a second
run of the script changes nothing.

Classes
-------
ScriptUnit
    Protocol of one unit.
HeaderUnit, ContextUnit, LogUnit, PreflightUnit, AttachUnit, FileUnit, CorrectUnit, ResultUnit
    The units, in the order of the script.
"""

import json
from typing import Any, Protocol

from pinax.plans.model import ChangePlan, CorrectOp, CreatorSpec


def literal(value: Any) -> str:
    """
    JavaScript literal of a JSON-serializable value.

    Parameters
    ----------
    value : Any
        Value to embed.

    Returns
    -------
    str
        JSON text, which JavaScript parses as the same value.

    Examples
    --------
    >>> literal({"key": "AB12", "path": "/tmp/a b.pdf"})
    '{"key": "AB12", "path": "/tmp/a b.pdf"}'
    """
    return json.dumps(value, ensure_ascii=False)


class ScriptUnit(Protocol):
    """Protocol of one unit."""

    def render(self, plan: ChangePlan) -> str:
        """
        Fragment of the script for a plan.

        Parameters
        ----------
        plan : ChangePlan
            Plan of the script.

        Returns
        -------
        str
            JavaScript fragment, empty when the plan gives the unit nothing to do.
        """


class HeaderUnit:
    """Comment stating how to run the script and what it returns."""

    def render(self, plan: ChangePlan) -> str:
        """Header comment."""
        return (
            "// Zotero script generated by pinax from a change plan.\n"
            '// Run: Tools > Developer > Run JavaScript, with "Run as async function" ticked.\n'
            "// The preflight stops before any write when a target is missing. Every step skips\n"
            "// what is already done, so a second run changes nothing. The script returns its\n"
            "// action log as JSON: save it beside the plan.\n"
            + "".join(f"// Destination: {d.path} ({d.key}).\n" for d in plan.destinations)
        )


class ContextUnit:
    """Library and lookup helper shared by the other units."""

    def render(self, plan: ChangePlan) -> str:
        """Definitions of `lib` and `getItem`."""
        del plan
        return (
            "const lib = Zotero.Libraries.userLibraryID;\n"
            "const getItem = key => Zotero.Items.getByLibraryAndKey(lib, key);\n"
        )


class LogUnit:
    """
    Action log: one record per step.

    A record holds the operation, the item, the outcome, a detail and, for a filing, the key of the
    collection.
    """

    def render(self, plan: ChangePlan) -> str:
        """Definitions of `log` and `record`."""
        del plan
        return (
            "const log = [];\n"
            'const record = (op, item, outcome, detail = "", collection = "") => '
            "log.push({ op, item, outcome, detail, collection });\n"
        )


class PreflightUnit:
    """
    Verification of every target before the first write.

    Every destination must exist under its key with its planned name, every item must exist outside
    the trash, every file to attach must exist, and every corrected field must be valid for the
    item type it is written to.
    """

    def render(self, plan: ChangePlan) -> str:
        """Preflight fragment; it throws, which stops the script, when a check fails."""
        files = [op.file.path for op in plan.attachments]
        destinations = [{"key": d.key, "name": d.name} for d in plan.destinations]
        fields = [
            {"item": op.item, "itemType": op.item_type, "fields": sorted(op.fields)}
            for op in plan.corrections
        ]
        return (
            f"const DESTINATIONS = {literal(destinations)};\n"
            f"const TARGET_ITEMS = {literal(plan.script_items())};\n"
            f"const TARGET_FILES = {literal(files)};\n"
            f"const TARGET_FIELDS = {literal(fields)};\n"
            "const collections = {};\n"
            "for (const { key, name } of DESTINATIONS) {\n"
            "  const collection = Zotero.Collections.getByLibraryAndKey(lib, key);\n"
            "  if (!collection || collection.deleted || collection.name !== name) {\n"
            "    throw new Error(`destination ${key} '${name}' not found`);\n"
            "  }\n"
            "  collections[key] = collection;\n"
            "}\n"
            "const missingItems = TARGET_ITEMS.filter(key => {\n"
            "  const item = getItem(key);\n"
            "  return !item || item.deleted;\n"
            "});\n"
            "if (missingItems.length) {\n"
            '  throw new Error("items missing or in the trash: " + missingItems.join(", "));\n'
            "}\n"
            "const missingFiles = [];\n"
            "for (const path of TARGET_FILES) {\n"
            "  if (!(await IOUtils.exists(path))) missingFiles.push(path);\n"
            "}\n"
            "if (missingFiles.length) {\n"
            '  throw new Error("files not found: " + missingFiles.join(", "));\n'
            "}\n"
            "const invalidFields = [];\n"
            "for (const target of TARGET_FIELDS) {\n"
            "  const type = target.itemType || getItem(target.item).itemType;\n"
            "  const typeID = Zotero.ItemTypes.getID(type);\n"
            "  if (!typeID) {\n"
            "    invalidFields.push(`${target.item}: type ${type}`);\n"
            "    continue;\n"
            "  }\n"
            "  for (const name of target.fields) {\n"
            "    const fieldID = Zotero.ItemFields.getID(name);\n"
            "    if (!fieldID || !Zotero.ItemFields.isValidForType(fieldID, typeID)) {\n"
            "      invalidFields.push(`${target.item}: ${name}`);\n"
            "    }\n"
            "  }\n"
            "}\n"
            "if (invalidFields.length) {\n"
            '  throw new Error("fields invalid for their type: " + invalidFields.join(", "));\n'
            "}\n"
            'record("preflight", "", "done", '
            "`${TARGET_ITEMS.length} items, ${TARGET_FILES.length} files`);\n"
        )


class AttachUnit:
    """Import of each planned PDF as a child of its item, skipped when the item has a PDF."""

    def render(self, plan: ChangePlan) -> str:
        """Attachment fragment, empty without attachments."""
        if not plan.attachments:
            return ""
        data = [{"item": op.item, "path": op.file.path} for op in plan.attachments]
        return (
            f"const ATTACH = {literal(data)};\n"
            "for (const { item: key, path } of ATTACH) {\n"
            "  const item = getItem(key);\n"
            "  const pdfs = item.getAttachments().map(id => Zotero.Items.get(id))\n"
            '    .filter(a => a.attachmentContentType === "application/pdf");\n'
            "  if (pdfs.length) {\n"
            '    record("attach", key, "skip", "the item has a PDF");\n'
            "    continue;\n"
            "  }\n"
            "  const attachment = await Zotero.Attachments.importFromFile("
            "{ file: path, parentItemID: item.id });\n"
            '  record("attach", key, "done", attachment.key);\n'
            "}\n"
        )


class FileUnit:
    """Addition of each planned item to its destination, skipped when it is already there."""

    def render(self, plan: ChangePlan) -> str:
        """Filing fragment, empty without filings."""
        if not plan.filings:
            return ""
        data = [{"item": op.item, "destination": op.destination} for op in plan.filings]
        return (
            f"const FILE = {literal(data)};\n"
            "for (const { item: key, destination } of FILE) {\n"
            "  const item = getItem(key);\n"
            "  const collection = collections[destination];\n"
            "  if (item.inCollection(collection.id)) {\n"
            '    record("file", key, "skip", "already in the destination", destination);\n'
            "    continue;\n"
            "  }\n"
            "  item.addToCollection(collection.id);\n"
            "  await item.saveTx();\n"
            '  record("file", key, "done", "", destination);\n'
            "}\n"
        )


def _creator(creator: CreatorSpec) -> dict[str, str]:
    """Creator in the form of `item.setCreators`; a creator without first name is one field."""
    if creator.first_name:
        return {
            "firstName": creator.first_name,
            "lastName": creator.last_name,
            "creatorType": creator.creator_type,
        }
    return {"name": creator.last_name, "creatorType": creator.creator_type}


def _correction(op: CorrectOp) -> dict[str, Any]:
    """Correction in the form read by the correction fragment."""
    return {
        "item": op.item,
        "itemType": op.item_type,
        "fields": op.fields,
        "creators": None if op.creators is None else [_creator(c) for c in op.creators],
        "carry": op.carry,
        "preserve": list(op.preserve),
    }


class CorrectUnit:
    """
    Correction of fields, type and creators.

    The fields named by `carry` and `preserve` are read before the type change, since the change
    drops the fields that the new type lacks. A preserved field invalid for the new type is
    appended to `extra` as `Name: value`, once.
    """

    def render(self, plan: ChangePlan) -> str:
        """Correction fragment, empty without corrections."""
        if not plan.corrections:
            return ""
        return (
            f"const CORRECT = {literal([_correction(op) for op in plan.corrections])};\n"
            "for (const op of CORRECT) {\n"
            "  const item = getItem(op.item);\n"
            "  const kept = {};\n"
            "  for (const name of [...Object.keys(op.carry), ...op.preserve]) {\n"
            "    kept[name] = item.getField(name);\n"
            "  }\n"
            "  if (op.itemType && item.itemType !== op.itemType) {\n"
            "    item.setType(Zotero.ItemTypes.getID(op.itemType));\n"
            "  }\n"
            "  const typeID = Zotero.ItemTypes.getID(item.itemType);\n"
            "  const valid = name => "
            "Zotero.ItemFields.isValidForType(Zotero.ItemFields.getID(name), typeID);\n"
            "  for (const [from, to] of Object.entries(op.carry)) {\n"
            "    if (kept[from] && valid(to) && !item.getField(to)) {\n"
            "      item.setField(to, kept[from]);\n"
            "    }\n"
            "  }\n"
            "  for (const name of op.preserve) {\n"
            "    if (!kept[name]) continue;\n"
            "    if (valid(name)) { item.setField(name, kept[name]); continue; }\n"
            "    const line = `${name}: ${kept[name]}`;\n"
            '    const extra = item.getField("extra") || "";\n'
            '    if (!extra.split("\\n").includes(line)) {\n'
            '      item.setField("extra", (extra + "\\n" + line).trim());\n'
            "    }\n"
            "  }\n"
            "  for (const [name, value] of Object.entries(op.fields)) item.setField(name, value);\n"
            "  if (op.creators) item.setCreators(op.creators);\n"
            "  await item.saveTx();\n"
            '  record("correct", op.item, "done", '
            '`${item.itemType}, citation key ${item.getField("citationKey")}`);\n'
            "}\n"
        )


class ResultUnit:
    """Return of the action log, shown by Zotero as the result of the script."""

    def render(self, plan: ChangePlan) -> str:
        """Final `return` statement."""
        del plan
        return "return JSON.stringify(log, null, 1);\n"
